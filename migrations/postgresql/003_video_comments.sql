-- Add only a new table. Existing application rows and columns are untouched.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
CREATE TABLE wgh.video_comment (
    comment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id bigint NOT NULL REFERENCES wgh.futsal_video(video_id) ON DELETE CASCADE,
    author_id bigint NOT NULL REFERENCES wgh.app_user(user_id) ON DELETE RESTRICT,
    content varchar(1000) NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 1000),
    time_seconds integer CHECK (time_seconds BETWEEN 0 AND 86400),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX video_comment_video_page ON wgh.video_comment(video_id,comment_id DESC);
ALTER TABLE wgh.video_comment ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON wgh.video_comment FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE wgh.video_comment_comment_id_seq FROM PUBLIC,anon,authenticated;
COMMIT;
