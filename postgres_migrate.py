"""Export the reviewed MySQL final DB; import into a NEW private PostgreSQL schema.

No DROP/TRUNCATE, no source writes, no automatic app connection change.
The target URL is read from an environment variable, never a command argument.
"""
import argparse
from datetime import datetime, date, time, timedelta, timezone
from decimal import Decimal
import hashlib
import json
import os
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parent
TABLES=['app_user','futsal_player','futsal_match','futsal_schedule','futsal_video',
        'match_player','player','video_analysis','video_event','wgh_google_identity',
        'wgh_user_role','wgh_account_consent','wgh_admin_request','wgh_role_history',
        'wgh_player_account','wgh_login_session','wgh_oauth_state']
EPHEMERAL={'wgh_login_session','wgh_oauth_state'}


def identifier(name):
    if not re.fullmatch('[a-z_][a-z_0-9]*',name):raise ValueError('Invalid schema identifier')
    return '"'+name+'"'


def literal(value):return "'"+str(value).replace("'","''")+"'"


def encode(value):
    if isinstance(value,(datetime,date,time)):return value.isoformat()
    if isinstance(value,timedelta):
        seconds=int(value.total_seconds())
        if not 0<=seconds<=86400:raise ValueError('MySQL duration cannot be migrated as a clock time')
        hours,seconds=divmod(seconds,3600);minutes,seconds=divmod(seconds,60)
        return f'{hours:02}:{minutes:02}:{seconds:02}'
    if isinstance(value,Decimal):return str(value)
    if value is None or isinstance(value,(str,int,float,bool)):return value
    raise ValueError('Unsupported source value type')


def pg_type(column):
    typ=column['DATA_TYPE'];source=column['COLUMN_TYPE']
    if typ=='bigint':return 'bigint'
    if typ in ('int','smallint','tinyint','mediumint'):return 'integer'
    if typ in ('varchar','char'):return f"{typ}({int(column['CHARACTER_MAXIMUM_LENGTH'])})"
    if typ in ('text','mediumtext','longtext'):return 'text'
    if typ in ('timestamp','datetime'):return 'timestamp without time zone'
    if typ=='time':return 'time without time zone'
    if typ=='date':return 'date'
    if typ=='enum':return 'varchar(30)'
    raise ValueError('Unsupported source type: '+source)


def schema_sql(metadata):
    statements=['-- Generated from the reviewed WGH MySQL schema. Apply only to a new target.',
        'CREATE SCHEMA wgh;', 'REVOKE ALL ON SCHEMA wgh FROM PUBLIC;',
        'SET LOCAL search_path TO wgh, pg_catalog;']
    foreign=[]
    for table in TABLES:
        meta=metadata[table];definitions=[]
        for c in meta['columns']:
            name=identifier(c['COLUMN_NAME']);typ=pg_type(c)
            definition=name+' '+typ
            if 'auto_increment' in c['EXTRA']:definition+=' GENERATED BY DEFAULT AS IDENTITY'
            elif c['COLUMN_DEFAULT'] is not None:
                default=c['COLUMN_DEFAULT']
                if str(default).upper()=='CURRENT_TIMESTAMP':definition+=" DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')"
                else:definition+=' DEFAULT '+literal(default)
            if c['IS_NULLABLE']=='NO':definition+=' NOT NULL'
            if c['DATA_TYPE']=='enum':
                options=c['COLUMN_TYPE'][5:-1]
                if not re.fullmatch(r"'[a-zA-Z_]+'(?:,'[a-zA-Z_]+')*",options):raise ValueError('Unsupported enum')
                definition+=' CHECK ('+name+' IN ('+options+'))'
            definitions.append(definition)
        definitions.append('PRIMARY KEY ('+','.join(identifier(x) for x in meta['primary'])+')')
        for check in meta['checks']:
            expression=check['CHECK_CLAUSE'].replace('`','"')
            definitions.append('CONSTRAINT '+identifier(check['CONSTRAINT_NAME'])+' CHECK ('+expression+')')
        statements.append('CREATE TABLE wgh.'+identifier(table)+' (\n  '+',\n  '.join(definitions)+'\n);')
        for index in meta['indexes']:
            columns=','.join(identifier(x) for x in index['columns'])
            if table=='app_user' and index['columns']==['email']:columns='lower(email)'
            statements.append('CREATE '+('UNIQUE ' if index['unique'] else '')+'INDEX '+identifier(table+'_'+index['name'])+' ON wgh.'+identifier(table)+' ('+columns+');')
        for fk in meta['foreign']:
            foreign.append('ALTER TABLE wgh.'+identifier(table)+' ADD CONSTRAINT '+identifier(fk['name'])+
                ' FOREIGN KEY ('+','.join(identifier(c) for c in fk['columns'])+') REFERENCES wgh.'+identifier(fk['table'])+
                ' ('+','.join(identifier(c) for c in fk['target_columns'])+') ON DELETE '+fk['delete']+';')
        statements.append('ALTER TABLE wgh.'+identifier(table)+' ENABLE ROW LEVEL SECURITY;')
    statements.extend(foreign)
    statements.extend([
        "CREATE FUNCTION wgh.touch_role_updated_at() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog AS $$ BEGIN NEW.updated_at := CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'; RETURN NEW; END $$;",
        'CREATE TRIGGER role_updated BEFORE UPDATE ON wgh.wgh_user_role FOR EACH ROW EXECUTE FUNCTION wgh.touch_role_updated_at();',
        'REVOKE ALL ON ALL TABLES IN SCHEMA wgh FROM PUBLIC;',
        'REVOKE ALL ON ALL SEQUENCES IN SCHEMA wgh FROM PUBLIC;',
        'REVOKE ALL ON ALL FUNCTIONS IN SCHEMA wgh FROM PUBLIC;',
        '-- Keep schema wgh OUT of Supabase Data API exposed schemas; FastAPI owns authorization.'
    ])
    return '\n\n'.join(statements)+'\n'


def export(destination):
    from dotenv import dotenv_values
    import pymysql
    env=dotenv_values(ROOT/'.env')
    if env.get('DB_NAME')!='futsaldb_test':raise ValueError('Export source must be the approved futsaldb_test')
    destination=Path(destination)
    if destination.exists():raise ValueError('Export destination already exists; choose a new directory')
    metadata={};data={}
    db=pymysql.connect(host=env.get('DB_HOST','localhost'),port=int(env.get('DB_PORT','3306')),
        user=env['DB_USER'],password=env['DB_PASSWORD'],database='futsaldb_test',
        cursorclass=pymysql.cursors.DictCursor,charset='utf8mb4',autocommit=False)
    try:
        with db.cursor() as cur:
            cur.execute("SET time_zone = '+09:00'")
            cur.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ')
            cur.execute('START TRANSACTION WITH CONSISTENT SNAPSHOT')
            cur.execute('SELECT TABLE_NAME,ENGINE,AUTO_INCREMENT FROM information_schema.TABLES WHERE TABLE_SCHEMA=%s',('futsaldb_test',))
            tables={x['TABLE_NAME']:x for x in cur.fetchall()}
            if set(tables)!=set(TABLES):raise ValueError('Source tables changed; review migration table inventory')
            if any(x['ENGINE']!='InnoDB' for x in tables.values()):raise ValueError('Source requires transaction-safe InnoDB tables')
            for table in TABLES:
                cur.execute('SELECT * FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=%s AND TABLE_NAME=%s ORDER BY ORDINAL_POSITION',('futsaldb_test',table))
                columns=[{k:c[k] for k in ['COLUMN_NAME','DATA_TYPE','COLUMN_TYPE','CHARACTER_MAXIMUM_LENGTH','EXTRA','IS_NULLABLE','COLUMN_DEFAULT']} for c in cur.fetchall()]
                cur.execute('SELECT INDEX_NAME,NON_UNIQUE,COLUMN_NAME FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=%s AND TABLE_NAME=%s ORDER BY INDEX_NAME,SEQ_IN_INDEX',('futsaldb_test',table))
                indexes={}
                for row in cur.fetchall():
                    idx=indexes.setdefault(row['INDEX_NAME'],{'name':row['INDEX_NAME'],'unique':row['NON_UNIQUE']==0,'columns':[]});idx['columns'].append(row['COLUMN_NAME'])
                primary=indexes.pop('PRIMARY')['columns']
                cur.execute('SELECT cc.CONSTRAINT_NAME,cc.CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS cc JOIN information_schema.TABLE_CONSTRAINTS tc ON cc.CONSTRAINT_SCHEMA=tc.CONSTRAINT_SCHEMA AND cc.CONSTRAINT_NAME=tc.CONSTRAINT_NAME WHERE tc.TABLE_SCHEMA=%s AND tc.TABLE_NAME=%s',('futsaldb_test',table))
                checks=list(cur.fetchall())
                cur.execute('''SELECT k.CONSTRAINT_NAME,k.COLUMN_NAME,k.REFERENCED_TABLE_NAME,k.REFERENCED_COLUMN_NAME,r.DELETE_RULE
                    FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r
                    ON k.CONSTRAINT_SCHEMA=r.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME=r.CONSTRAINT_NAME AND k.TABLE_NAME=r.TABLE_NAME
                    WHERE k.TABLE_SCHEMA=%s AND k.TABLE_NAME=%s ORDER BY k.CONSTRAINT_NAME,k.ORDINAL_POSITION''',('futsaldb_test',table))
                foreign={}
                for row in cur.fetchall():
                    fk=foreign.setdefault(row['CONSTRAINT_NAME'],{'name':row['CONSTRAINT_NAME'],'columns':[],'table':row['REFERENCED_TABLE_NAME'],'target_columns':[],'delete':row['DELETE_RULE']})
                    if fk['delete'] not in ('RESTRICT','NO ACTION','CASCADE','SET NULL'):raise ValueError('Unsupported foreign key rule')
                    fk['columns'].append(row['COLUMN_NAME']);fk['target_columns'].append(row['REFERENCED_COLUMN_NAME'])
                metadata[table]={'columns':columns,'primary':primary,'indexes':list(indexes.values()),'foreign':list(foreign.values()),'checks':checks,'next_id':tables[table]['AUTO_INCREMENT']}
                cur.execute('SELECT * FROM `'+table+'` ORDER BY '+','.join('`'+key+'`' for key in primary))
                rows=list(cur.fetchall())
                data[table]=[] if table in EPHEMERAL else [{key:encode(value) for key,value in row.items()} for row in rows]
        db.rollback()  # Read-only consistent snapshot, never commit source data.
    finally:db.close()
    destination.mkdir(parents=True)
    (destination/'schema.sql').write_text(schema_sql(metadata),encoding='utf-8')
    (destination/'data.json').write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8')
    report={'version':1,'source_database':'futsaldb_test','source_clock_timezone':'+09:00',
            'created_at':datetime.now(timezone.utc).isoformat(),'excluded_ephemeral_tables':sorted(EPHEMERAL),
            'tables':metadata,'counts':{key:len(value) for key,value in data.items()},
            'sha256':{n:hashlib.sha256((destination/n).read_bytes()).hexdigest() for n in ['schema.sql','data.json']}}
    (destination/'manifest.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    print('EXPORT VERIFIED:',len(data),'tables,',sum(map(len,data.values())),'durable rows. Session/OAuth state excluded.')


def read_bundle(directory):
    directory=Path(directory);manifest=json.loads((directory/'manifest.json').read_text(encoding='utf-8'))
    if manifest.get('version')!=1 or set(manifest['tables'])!=set(TABLES):raise ValueError('Unsupported migration bundle')
    for name in ['schema.sql','data.json']:
        if hashlib.sha256((directory/name).read_bytes()).hexdigest()!=manifest['sha256'][name]:raise ValueError('Migration bundle checksum mismatch')
    data=json.loads((directory/'data.json').read_text(encoding='utf-8'))
    if set(data)!=set(TABLES):raise ValueError('Unexpected migration tables')
    for table in TABLES:
        if len(data[table])!=manifest['counts'][table]:raise ValueError('Migration bundle row count mismatch')
        if table in EPHEMERAL and data[table]:raise ValueError('Live sessions must not be migrated')
    return manifest,data,(directory/'schema.sql').read_text(encoding='utf-8')


def decoded_row(row,columns):
    result=[]
    for col in columns:
        value=row[col['COLUMN_NAME']];typ=col['DATA_TYPE']
        if value is not None:
            if typ=='date':value=date.fromisoformat(value)
            elif typ in ('timestamp','datetime'):value=datetime.fromisoformat(value)
            elif typ=='time':
                # psycopg time supports 00:00..23:59. MySQL time=24:00 needs explicit review.
                value=time.fromisoformat(value)
        result.append(value)
    return result


def compare(cur,manifest,data):
    from psycopg import sql
    for table in TABLES:
        meta=manifest['tables'][table]
        cur.execute(sql.SQL('SELECT * FROM wgh.{} ORDER BY {}').format(sql.Identifier(table),sql.SQL(',').join(map(sql.Identifier,meta['primary']))))
        actual=[{key:encode(value) for key,value in row.items()} for row in cur.fetchall()]
        if actual!=data[table]:raise ValueError('PostgreSQL row content mismatch: '+table)


def target_connection(variable):
    import psycopg
    from psycopg.rows import dict_row
    from dotenv import dotenv_values
    url=os.getenv(variable,'') or dotenv_values(ROOT/'.env.supabase').get(variable,'')
    if not url:raise ValueError('Set '+variable+' privately in the terminal or hosting secret settings')
    return psycopg.connect(url,row_factory=dict_row,prepare_threshold=None,connect_timeout=15)


def apply(directory,variable,confirmed):
    if not confirmed:raise ValueError('Import requires --apply-new-schema; existing schemas are always rejected')
    from psycopg import sql
    manifest,data,ddl=read_bundle(directory)
    with target_connection(variable) as db:
        with db.cursor() as cur:
            cur.execute("SELECT to_regnamespace('wgh') AS existing")
            if cur.fetchone()['existing'] is not None:raise ValueError('Target wgh schema already exists. Nothing was changed.')
            cur.execute("SET LOCAL TIME ZONE 'Asia/Seoul'")
            cur.execute(ddl,prepare=False)
            for table in TABLES:
                columns=manifest['tables'][table]['columns'];names=[c['COLUMN_NAME'] for c in columns]
                statement=sql.SQL('INSERT INTO wgh.{} ({}) VALUES ({})').format(sql.Identifier(table),sql.SQL(',').join(map(sql.Identifier,names)),sql.SQL(',').join(sql.Placeholder() for _ in names))
                if data[table]:cur.executemany(statement,[decoded_row(row,columns) for row in data[table]])
                identity=next((c['COLUMN_NAME'] for c in columns if 'auto_increment' in c['EXTRA']),None)
                if identity:
                    next_id=max(manifest['tables'][table]['next_id'] or 1,max((row[identity]+1 for row in data[table]),default=1))
                    cur.execute('SELECT setval(pg_get_serial_sequence(%s,%s),%s,false)',('wgh.'+table,identity,next_id))
            compare(cur,manifest,data)
        # Commit only after every full row and foreign key has passed verification.
    print('IMPORT VERIFIED AND COMMITTED. Full rows, ids, relationships and durable records preserved.')


def verify(directory,variable):
    manifest,data,_=read_bundle(directory)
    with target_connection(variable) as db:
        with db.cursor() as cur:
            cur.execute('SET TRANSACTION READ ONLY')
            compare(cur,manifest,data)
    print('VERIFY PASSED: all imported table rows match the migration snapshot.')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode',choices=['export','import','verify'])
    parser.add_argument('--directory',required=True)
    parser.add_argument('--url-env',default='WGH_MIGRATION_DATABASE_URL')
    parser.add_argument('--apply-new-schema',action='store_true')
    args=parser.parse_args()
    try:
        if args.mode=='export':export(args.directory)
        elif args.mode=='import':apply(args.directory,args.url_env,args.apply_new_schema)
        else:verify(args.directory,args.url_env)
    except Exception as error:
        # Driver errors can contain private SQL row values or the connection URL.
        import pymysql
        import psycopg
        if isinstance(error,(pymysql.MySQLError,psycopg.Error)):
            parser.exit(1,'Database operation failed; no connection secrets printed. Existing target data was not replaced.\n')
        parser.exit(1,str(error)+'\n')


if __name__=='__main__':main()
