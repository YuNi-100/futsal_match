const {chromium}=require('playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..','public');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 try{
  const page=await browser.newPage({viewport:{width:1366,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const player={player_id:7,player_name:'정선수',back_number:7,position:'ALA',joined_at:'2025-01-01',appearances:2,goals:3,assists:1};
  const matches=[{match_id:6,match_date:'2026-10-15',opponent:'은평FC',our_score:3,opponent_score:2,result:'win',goals:2,assists:1,has_video:1},{match_id:3,match_date:'2026-10-01',opponent:'다른 상대',our_score:1,opponent_score:0,result:'win',goals:1,assists:0,has_video:0}];
  let empty=false;
  let matchHasVideo=true;
  await page.route('**/*',async route=>{
   const u=new URL(route.request().url());
   if(u.hostname!=='wgh.test')return route.fulfill({body:''});
   if(u.pathname==='/auth/me')return route.fulfill({json:{user:null,csrf_token:null}});
   if(u.pathname==='/api/players/7')return route.fulfill({json:{success:true,data:{...player,matches:empty?[]:matches}}});
   if(u.pathname==='/api/players/999')return route.fulfill({status:404,json:{detail:'선수 정보를 찾을 수 없습니다.'}});
   if(u.pathname==='/api/players')return route.fulfill({json:{success:true,data:[player]}});
   if(u.pathname==='/api/matches/6')return route.fulfill({json:{success:true,data:{...matches[0],location:'풋살장',memo:'기록',start_time:null,end_time:null,players:[{...player,goals:2}],videos:matchHasVideo?[{video_id:1}]:[]}}});
   if(u.pathname==='/api/youtube-videos')return route.fulfill({json:{success:true,data:[{video_id:1,match_id:6,title:'은평 경기 영상',youtube_id:'abcdefghijk'}]}});
   if(u.pathname.startsWith('/api/'))return route.fulfill({json:{success:true,data:[]}});
   return route.fulfill({path:path.join(root,u.pathname==='/'?'index.html':u.pathname.slice(1))});
  });
  await page.goto('http://wgh.test/match.html?match_id=6');
  await page.waitForSelector('#detailPlayers .player-record-link');
  await page.locator('#detailPlayers .player-record-link').click();
  await page.waitForSelector('#playerDetail:not([hidden])');
  assert.equal(new URL(page.url()).searchParams.get('player_id'),'7');
  assert.equal(await page.locator('#playerName').textContent(),'정선수');
  assert.equal(await page.locator('#goals').textContent(),'3');
  assert.match(await page.locator('.side-menu .active').textContent(),/선수 정보/);
  assert.equal(await page.locator('#playerMatches tr').count(),2);
  assert.equal(await page.locator('#playerMatches a[href^="/video.html"]').count(),1);
  assert.equal(await page.locator('#playerBack').getAttribute('href'),'/match.html?match_id=6');
  await page.screenshot({path:'C:/Users/EZ/.codex/.chatgpt-projects/g-p-6ac594379aec8191a402e9b21ce9cc51/player-profile-preview.png',fullPage:true});
  await page.locator('#playerMatches a[href^="/video.html"]').click();
  await page.waitForSelector('.video-list-item');
  assert.equal(new URL(page.url()).searchParams.get('match_id'),'6');
  await page.goto('http://wgh.test/');
  await page.waitForSelector('a.player-item');
  const homeCard=page.locator('a.player-item').first();
  assert.equal(await homeCard.locator('a').count(),0);
  await homeCard.locator('.player-stats').click();
  await page.waitForSelector('#playerDetail:not([hidden])');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#playerName').isVisible(),true);
  await page.locator('#playerMatches a[href^="/match.html"]').first().click();
  await page.waitForSelector('#matchDetail:not([hidden])');
  await page.locator('#detailScorers a').click();
  await page.waitForSelector('.video-list-item');
  assert.equal(new URL(page.url()).pathname,'/video.html');
  assert.equal(new URL(page.url()).searchParams.get('match_id'),'6');
  matchHasVideo=false;
  await page.goto('http://wgh.test/match.html?match_id=6');
  await page.waitForSelector('#matchDetail:not([hidden])');
  assert.equal(await page.locator('#detailScorers a').count(),0);
  assert.match(await page.locator('#detailScorers').textContent(),/경기 영상 미등록/);
  assert.equal(await page.locator('#detailPlayers a').count(),1);
  empty=true;
  await page.goto('http://wgh.test/player.html?player_id=7');
  await page.waitForSelector('#playerMatchesEmpty:not([hidden])');
  await page.goto('http://wgh.test/player.html?player_id=999');
  await page.waitForFunction(()=>document.querySelector('#playerStatus').textContent.includes('찾을 수 없습니다'));
  assert.deepEqual(errors,[]);
  console.log('PASS: whole home card → player, participant → player, scorer → match video, no-video notice, profile/history, mobile, empty/404');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
